#!/usr/bin/env python3
"""Render public fixture values into bounded Rust experiment inputs, never runtime claims."""
from __future__ import annotations
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def need(condition, message):
    if not condition:
        raise ValueError(message)


def literal(value):
    need(isinstance(value, str) and not any(ord(c) < 32 for c in value), "Invalid fixture string")
    need(len(value.encode()) <= 8192, "Fixture string exceeds frozen bound")
    return json.dumps(value, ensure_ascii=False)


def epoch(value):
    if isinstance(value, str):
        parsed = datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
        value = int(parsed.timestamp()) * 1000
    need(type(value) is int and -(2**63) <= value < 2**63, "Invalid native integer")
    return value


def vector(values):
    return "vec![" + ", ".join(values) + "]"


def clause(value, depth=0):
    need(type(value) is dict and len(value) == 1 and depth <= 8, "Unbounded/unknown research query")
    kind, body = next(iter(value.items()))
    if kind == "match_all":
        need(body == {}, "Unexpected match_all options")
        return "Clause::MatchAllDocs(MatchAllDocsQuery::new(128))"
    if kind == "bool":
        need(set(body) <= {"must", "filter", "should", "must_not", "minimum_should_match"}, "Unknown bool option")
        fields = []
        for name in ["must", "filter", "should", "must_not"]:
            items = body.get(name, [])
            need(type(items) is list and len(items) <= 16, "Too many query clauses")
            fields.append(name + ": " + vector([clause(x, depth + 1) for x in items]))
        msm = body.get("minimum_should_match", 0)
        need(type(msm) is int and 0 <= msm <= 16, "Invalid minimum_should_match")
        return "Clause::Boolean(Box::new(BooleanQuery { " + ", ".join(fields) + f", minimum_should_match: {msm}" + " }))"
    need(type(body) is dict and len(body) == 1, "Unknown field query")
    field, arg = next(iter(body.items()))
    need(field in {"uid", "tenant", "category", "title", "price", "active", "created_at"}, "Unknown field")
    if kind == "term":
        need(type(arg) in (str, bool), "Unexpected term type")
        text = str(arg).lower() if isinstance(arg, bool) else arg
        return f"term({literal(field)}, {literal(text)})"
    if kind == "terms":
        need(type(arg) is list and 1 <= len(arg) <= 16, "Unbounded terms query")
        return "Clause::Boolean(Box::new(BooleanQuery { should: " + vector([f"term({literal(field)}, {literal(x)})" for x in arg]) + ", minimum_should_match: 1, ..Default::default() }))"
    if kind in {"match", "match_phrase"}:
        need(field == "title" and type(arg) is str, "Unknown analyzed field")
        return f"analyzed({literal(arg)}, {str(kind == 'match_phrase').lower()})"
    if kind == "range":
        need(field in {"price", "created_at"} and set(arg) <= {"gte", "gt", "lte", "lt"}, "Unknown numeric range")
        low = epoch(arg["gte"]) if "gte" in arg else epoch(arg["gt"]) + 1 if "gt" in arg else -(2**63)
        high = epoch(arg["lte"]) if "lte" in arg else epoch(arg["lt"]) - 1 if "lt" in arg else 2**63 - 1
        need(-(2**63) <= low <= high < 2**63, "Invalid inclusive range")
        return f"Clause::PointsRange(PointsRangeQuery::new({literal(field)}, {low}, {high}))"
    raise ValueError("Operator outside frozen research translator")


def render(root=ROOT):
    folder = root / "fixtures/api/core-v1"
    envelope = json.loads((root / "docs/plan/research/native-engine-envelope.json").read_text(encoding="utf-8"))
    data = {}
    for name, digest in envelope["source"]["fixture_sha256"].items():
        raw = (folder / name).read_bytes()
        need(0 < len(raw) <= 65536 and hashlib.sha256(raw).hexdigest() == digest, "Frozen fixture changed: " + name)
        data[name] = json.loads(raw)
    rows = data["documents.json"]
    need(len(rows) == 11 and len({x["id"] for x in rows}) == 11, "Core document inventory changed")
    out = ["// Generated by tools/engine_research.py render from hash-bound public fixtures.", "// Research inputs/oracles only; not a native runtime or wire compatibility claim.", "fn core_rows() -> Vec<Row<'static>> { vec!["]
    for item in rows:
        row = item["source"]
        need(item["id"] == row["uid"] and len(row) == 7, "Invalid core row")
        values = [n + ": " + literal(row[n]) for n in ["uid", "tenant", "category", "title"]]
        need(type(row["active"]) is bool, "Invalid active flag")
        values += ["price: " + str(epoch(row["price"])), "active: " + str(row["active"]).lower(), "created_at: " + str(epoch(row["created_at"]))]
        out.append("Row { " + ", ".join(values) + " },")
    out += ["] }", "fn search_cases() -> Vec<SearchCase> { vec!["]
    for case in data["search-cases.json"]:
        oracle = case["reference_oracle"]
        if oracle["kind"] != "hits":
            continue
        body = case["request"]["json"]
        sorts = []
        for entry in body["sort"]:
            field, direction = next(iter(entry.items()))
            need(direction in {"asc", "desc"}, "Unknown sort direction")
            if field == "_score":
                need(direction == "desc", "Unknown score order")
                sorts.append("SortField::score()")
            else:
                need(field in {"uid", "price"}, "Unknown sort field")
                sorts.append(f"SortField::numeric({literal(field)}, SortType::{'String' if field == 'uid' else 'Long'}, {str(direction == 'desc').lower()})")
        out.append("SearchCase { id: " + literal(case["id"]) + ", query: top(" + clause(body["query"]) + "), sort: " + vector(sorts) + ", size: " + str(min(body["size"], 128)) + ", ids: " + vector([literal(x) for x in oracle["ids"]]) + ", total: " + str(oracle["exact_total"]) + " },")
    out += ["] }", "fn analyzer_cases() -> Vec<AnalyzerCase> { vec!["]
    for case in data["analyzer-cases.json"]:
        tokens = [f"({literal(x['token'])}, {x['position']}, {x['start_offset']}, {x['end_offset']})" for x in case["tokens"]]
        out.append(f"AnalyzerCase {{ id: {literal(case['id'])}, text: {literal(case['text'])}, tokens: {vector(tokens)} }},")
    out += ["] }"]
    metrics = next(x for x in data["search-cases.json"] if x["id"] == "finite-metrics")["reference_oracle"]["values"]
    out.append("const METRICS: (f64, f64, f64, u64) = (" + ", ".join(str(float(metrics[x])) for x in ["sum_price", "min_price", "max_price"]) + ", " + str(metrics["count_price"]) + ");")
    terms = next(x for x in data["search-cases.json"] if x["id"] == "finite-key-ordered-terms")["reference_oracle"]["values"]["categories"]
    out.append("const TERMS: &[(&str, u64)] = &[" + ", ".join(f"({literal(x['key'])}, {x['doc_count']})" for x in terms) + "];")
    held_raw = (root / "fixtures/engine-research/held-out.json").read_bytes()
    need(len(held_raw) <= 65536 and hashlib.sha256(held_raw).hexdigest() == envelope["held_out_sha256"], "Frozen held-out controls changed")
    held = json.loads(held_raw)
    out.append("const PHRASE_ROWS: &[(&str, &str)] = &[" + ", ".join(f"({literal(x['id'])}, {literal(x['title'])})" for x in held["phrase"]["documents"]) + "];")
    out.append("const PHRASE_IDS: &[&str] = &[" + ", ".join(literal(x) for x in held["phrase"]["exact_phrase_ids"]) + "];")
    out.append("const WRONG_AND_IDS: &[&str] = &[" + ", ".join(literal(x) for x in held["phrase"]["unsafe_unordered_and_ids"]) + "];")
    out.append("const DATE_ROWS: &[(&str, i64)] = &[" + ", ".join(f"({literal(x['id'])}, {epoch(x['epoch_ms'])})" for x in held["date"]["documents"]) + "];")
    out.append("const DATE_IDS: &[&str] = &[" + ", ".join(literal(x) for x in held["date"]["inclusive_range_ids"]) + "];")
    out.append(f"const DATE_RANGE: (i64, i64) = ({epoch(held['date']['minimum'])}, {epoch(held['date']['maximum'])});")
    return "\n".join(out) + "\n"


def sample_commands(root=ROOT):
    """Fixed fresh-process repeats, additional to the complete ordinary suites."""
    envelope = json.loads((root / "docs/plan/research/native-engine-envelope.json").read_text(encoding="utf-8"))
    need(envelope["matrix"]["profiles"] == ["dev", "release"] and envelope["resource_limits"]["fresh_process_repetitions"] == 3,
         "Research sample matrix changed without runner qualification")
    return [(profile, repetition, ["cargo", "nextest", "run", "--locked", "--offline", "--package", "hsearch-engine", "--all-features",
            "--test", "native_feasibility", *(["--release"] if profile == "release" else []), "--profile", "hsearch", "--no-tests=fail", "--success-output", "immediate"])
            for profile in ("dev", "release") for repetition in (1, 2, 3)]


def run_samples(run):
    """Emit completion only after the caller's checked native command succeeds."""
    for profile, repetition, command in sample_commands():
        event = {"profile": profile, "repetition": repetition}
        print(json.dumps({"native_engine_research": dict(event, state="started")}), flush=True)
        run(command)
        print(json.dumps({"native_engine_research": dict(event, state="completed")}), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["render", "check"])
    args = parser.parse_args()
    try:
        expected = render()
        path = ROOT / "crates/engine/tests/fixtures/native_core.rs"
        if args.command == "render":
            path.write_text(expected, encoding="utf-8", newline="\n")
        else:
            need(path.read_text(encoding="utf-8") == expected, "Native fixture projection is stale")
        print("PASS: hash-bound public fixture projection; no native execution or compatibility acceptance")
        return 0
    except (ValueError, OSError, KeyError, TypeError) as error:
        print("FAIL: " + str(error))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
